"""Rebuild the quiz's eBird regions from saved all-time Bird List HTML.

Usage: python3 scripts/rebuild-bird-regions.py AVILIST_XLSX EBIRD_NAMES_XLSX REGION_HTML_DIR
Requires openpyxl. Save each https://ebird.org/region/<code>/bird-list page as
<code>.html in REGION_HTML_DIR. Region codes and labels come from the quiz data.
"""

import argparse
from collections import defaultdict
from html import unescape
import json
from pathlib import Path
import re

from openpyxl import load_workbook


QUIZ = Path(__file__).resolve().parents[1] / "games" / "world-birds"
REGION_FILE = QUIZ / "ebird-regions.js"
ROW = re.compile(
    r'<li id="([^"]+)" class="BirdList-list-list-item countable">.*?'
    r'<span class="Species-sci Species-sub">(.*?)</span>',
    re.DOTALL,
)


def read_data(path, binding):
    return json.loads(path.read_text(encoding="utf-8").split(binding, 1)[1].strip().removesuffix(";"))


def read_avilist(path, species):
    parents = {}
    names = defaultdict(set)
    with path.open("rb") as source:
        workbook = load_workbook(source, read_only=True, data_only=True)
        for row in workbook["AviList v2026"].iter_rows(min_row=2, max_col=20, values_only=True):
            rank, scientific, concept = row[1], row[4], row[19]
            if rank != "subspecies":
                continue
            genus, species_name, epithet = scientific.casefold().split()
            parent = species.get(f"{genus} {species_name}")
            if parent:
                if concept:
                    parents[concept] = parent
                names[f"{genus} {epithet}"].add(parent)
        workbook.close()
    return parents, names


def read_ebird(path):
    with path.open("rb") as source:
        workbook = load_workbook(source, read_only=True, data_only=True)
        concepts = {
            code: concept for _, rank, code, concept in
            workbook["Sparse"].iter_rows(min_row=2, max_col=4, values_only=True)
            if rank == "species"
        }
        workbook.close()
    return concepts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("avilist", type=Path)
    parser.add_argument("ebird_names", type=Path)
    parser.add_argument("html_dir", type=Path)
    args = parser.parse_args()

    orders = read_data(QUIZ / "avilist-v2026.js", "const aviListV2026 = ")
    species = {
        scientific.casefold(): concept
        for _, _, families in orders
        for _, _, birds in families
        for concept, _, scientific, *_ in birds
    }
    species_ids = set(species.values())
    parent_by_id, parents_by_name = read_avilist(args.avilist, species)
    ebird_concepts = read_ebird(args.ebird_names)
    output = []
    unresolved = set()

    for code, label, previous in read_data(REGION_FILE, "const ebirdRegions = "):
        source = (args.html_dir / f"{code}.html").read_text(encoding="utf-8")
        rows = ROW.findall(source)
        if (f"<title>Bird List - {label} - eBird</title>" not in source
                or not rows or len(rows) != source.count('class="BirdList-list-list-item countable"')):
            raise SystemExit(f"Could not verify the eBird Bird List for {label} ({code}).")

        members = set()
        for ebird_code, scientific in rows:
            name = unescape(scientific).strip().casefold()
            concept = ebird_concepts.get(ebird_code)
            if concept in species_ids:
                members.add(concept)
                continue

            # Different checklists may recognize the same population at different ranks.
            match = parent_by_id.get(concept) or species.get(name)
            if not match:
                possible = parents_by_name.get(name, set())
                if len(possible) == 1:
                    match = next(iter(possible))
            if match:
                members.add(match)
            else:
                unresolved.add((ebird_code, name))

        output.append([code, label, sorted(members)])
        print(f"{label}: {len(members)} species (+{len(members - set(previous))}, -{len(set(previous) - members)})")

    if unresolved:
        raise SystemExit("Unresolved taxa. Review these before regenerating:\n" +
                         "\n".join(f"{code}: {name}" for code, name in sorted(unresolved)))

    data = ",\n".join("  " + json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in output)
    REGION_FILE.write_text(
        "// eBird all-time regional bird lists: https://ebird.org/region/<region-code>/bird-list\n"
        "// Matched to AviList v2026 by concept ID, scientific name, or subspecies parent.\n"
        "// Generated by scripts/rebuild-bird-regions.py.\n"
        f"const ebirdRegions = [\n{data}\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
